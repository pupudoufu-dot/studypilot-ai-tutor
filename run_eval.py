"""Compare a naive baseline with the StudyPilot routing policy."""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from studypilot.diagnosis import DiagnosisAgent  # noqa: E402
from studypilot.models import ErrorType  # noqa: E402
from studypilot.tutor import TutorAgent  # noqa: E402


def percentage(value: int, total: int) -> float:
    return round(100 * value / total, 1) if total else 0.0


def load_cases() -> list[dict[str, object]]:
    path = ROOT / "evals" / "cases.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def evaluate(cases: list[dict[str, object]]) -> dict[str, object]:
    agent = DiagnosisAgent()
    tutor = TutorAgent()
    total = len(cases)
    counters: Counter[str] = Counter()
    bad_cases: list[dict[str, object]] = []

    for case in cases:
        expected = ErrorType(str(case["expected_error_type"]))
        reasoning = str(case["student_reasoning"])
        baseline = agent.diagnose(reasoning, mode="baseline")
        optimized = agent.diagnose(reasoning, mode="optimized")

        counters["baseline_correct"] += baseline.error_type == expected
        counters["optimized_correct"] += optimized.error_type == expected

        if optimized.is_low_confidence:
            counters["low_confidence_cases"] += 1
            counters["baseline_low_conf_hard_decisions"] += (
                baseline.error_type != ErrorType.NEEDS_CLARIFICATION
            )
            counters["optimized_low_conf_hard_decisions"] += (
                optimized.error_type != ErrorType.NEEDS_CLARIFICATION
            )

        # The baseline comparator exposes the stored answer on its first turn.
        counters["baseline_first_turn_answer_exposure"] += 1
        hint = tutor.next_hint(optimized.error_type, attempts=0, budget=3)
        counters["optimized_first_turn_answer_exposure"] += hint.reveals_answer

        if optimized.error_type != expected:
            bad_cases.append(
                {
                    "case_id": case["case_id"],
                    "expected": expected.value,
                    "predicted": optimized.error_type.value,
                    "confidence": optimized.confidence,
                    "reasoning": reasoning,
                }
            )

    low_conf_total = counters["low_confidence_cases"]
    metrics = {
        "dataset": {
            "cases": total,
            "knowledge_points": len({case["knowledge_point"] for case in cases}),
            "error_types": len({case["expected_error_type"] for case in cases}),
            "source": "synthetic",
        },
        "diagnosis_accuracy": {
            "baseline_count": counters["baseline_correct"],
            "baseline_percent": percentage(counters["baseline_correct"], total),
            "optimized_count": counters["optimized_correct"],
            "optimized_percent": percentage(counters["optimized_correct"], total),
        },
        "low_confidence_hard_decision_rate": {
            "cases": low_conf_total,
            "baseline_count": counters["baseline_low_conf_hard_decisions"],
            "baseline_percent": percentage(
                counters["baseline_low_conf_hard_decisions"], low_conf_total
            ),
            "optimized_count": counters["optimized_low_conf_hard_decisions"],
            "optimized_percent": percentage(
                counters["optimized_low_conf_hard_decisions"], low_conf_total
            ),
        },
        "first_turn_answer_exposure_rate": {
            "baseline_count": counters["baseline_first_turn_answer_exposure"],
            "baseline_percent": percentage(
                counters["baseline_first_turn_answer_exposure"], total
            ),
            "optimized_count": counters["optimized_first_turn_answer_exposure"],
            "optimized_percent": percentage(
                counters["optimized_first_turn_answer_exposure"], total
            ),
        },
        "bad_cases": bad_cases,
        "limitations": [
            "Synthetic benchmark; it does not measure real learner outcomes.",
            "Rule-based classifier; results do not represent general LLM quality.",
            "Baseline is a documented comparator, not a third-party product.",
        ],
    }
    return metrics


def render_report(metrics: dict[str, object]) -> str:
    dataset = metrics["dataset"]
    accuracy = metrics["diagnosis_accuracy"]
    hard = metrics["low_confidence_hard_decision_rate"]
    exposure = metrics["first_turn_answer_exposure_rate"]
    return f"""# Offline Evaluation Report

This report is generated by `python scripts/run_eval.py`.

## Dataset

- {dataset['cases']} synthetic cases
- {dataset['knowledge_points']} knowledge points
- {dataset['error_types']} predefined error types
- No real students or production traffic

## Results

| Metric | Baseline | StudyPilot |
|---|---:|---:|
| Diagnosis accuracy | {accuracy['baseline_count']}/{dataset['cases']} ({accuracy['baseline_percent']}%) | {accuracy['optimized_count']}/{dataset['cases']} ({accuracy['optimized_percent']}%) |
| Hard decisions on low-confidence cases | {hard['baseline_count']}/{hard['cases']} ({hard['baseline_percent']}%) | {hard['optimized_count']}/{hard['cases']} ({hard['optimized_percent']}%) |
| First-turn answer exposure | {exposure['baseline_count']}/{dataset['cases']} ({exposure['baseline_percent']}%) | {exposure['optimized_count']}/{dataset['cases']} ({exposure['optimized_percent']}%) |

## Interpretation

The benchmark checks whether the workflow follows its own diagnosis and hinting
policy. It does **not** establish learning gains, retention, conversion, or real
student behavior. See `docs/evaluation-methodology.md` and `docs/limitations.md`.
"""


def main() -> None:
    cases = load_cases()
    metrics = evaluate(cases)
    (ROOT / "evals" / "results.json").write_text(
        json.dumps(metrics, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    (ROOT / "evals" / "report.md").write_text(render_report(metrics), encoding="utf-8")
    print(render_report(metrics))


if __name__ == "__main__":
    main()

